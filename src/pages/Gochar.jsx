function sadesati(moonRashi, T) {
  if (moonRashi === "Meena") return T.sade.peak;
  if (moonRashi === "Kumbha") return T.sade.last;
  if (moonRashi === "Mesha") return T.sade.first;
  if (moonRashi === "Mithuna" || moonRashi === "Tula") return T.sade.dhaiya;
  return T.sade.none;
}

