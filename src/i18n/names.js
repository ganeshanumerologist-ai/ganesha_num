// Panchang object (astro.js ka panchang()) ko bhasha ke hisaab se localise karta hai.
// Isse har page par ek hi call se tithi/nakshatra/yoga/karana/rashi sab bhasha me.
export function LP(p, lang) {
  if (!p) return p;
  const t = namesTX(lang);
  const ri = (name) => {
    const i = EN.rashi.indexOf(name);
    return i >= 0 ? t.rashi[i] : name;
  };
  return {
    ...p,
    suryaRashi: ri(p.suryaRashi),
    chandraRashi: ri(p.chandraRashi),
    nakshatra: { ...p.nakshatra, name: t.nak[p.nakshatra.index] ?? p.nakshatra.name },
    tithi: {
      ...p.tithi,
      name: t.tithi[(p.tithi.n - 1) % 15] ?? p.tithi.name,
      paksha: t.paksha[p.tithi.paksha] ?? p.tithi.paksha,
    },
    yoga: yogaName(p.yoga, lang),
    karana: karanaName(p.karana, lang),
  };
}

