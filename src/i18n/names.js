function resolve(lang) {
  const chain = langChain(lang);
  let out = E2.en;
  for (let i = chain.length - 1; i >= 0; i--) {
    const code = chain[i];
    const d = ALL[code];
    const d2 = E2[code];
    if (!d && !d2) continue;
    const src = d || {};
    const y2 = d2 || {};
    out = {
      rashi: src.rashi || out.rashi,
      graha: { ...out.graha, ...(src.graha || {}) },
      nak: src.nak || out.nak,
      tithi: src.tithi || out.tithi,
      paksha: { ...out.paksha, ...(src.paksha || {}) },
      vaar: src.vaar || out.vaar,
      chog: { ...out.chog, ...(src.chog || {}) },
      yoga: y2.yoga || out.yoga,
      karana: y2.karana || out.karana,
      tara: y2.tara || out.tara,
      vrat: { ...out.vrat, ...(VR[code] || {}) },
      sth: { ...out.sth, ...(ST[code] || {}) },
    };
  }
  return out;
}

