const cache = new Map();

export function adminTX(lang) {
  if (cache.has(lang)) return cache.get(lang);
  const chain = langChain(lang);
  let out = EN;
  // English sabse neeche, phir chain ke order me upar.
  for (let i = chain.length - 1; i >= 0; i--) {
    const d = D[chain[i]];
    if (d) out = { ...out, ...d };
  }
  cache.set(lang, out);
  return out;
}

