export function reduceToDigit(n) {
  let v = Number(n);
  while (v > 9) {
    v = String(v).split("").reduce((a, b) => a + Number(b), 0);
  }
  return v;
}

// Personal year = day + month + year digits reduced
export function personalYear(birthdate, year) {
  if (!birthdate || !year) return null;
  const parts = birthdate.split("-");
  if (parts.length < 3) return null;
  const day = Number(parts[2]);
  const month = Number(parts[1]);
  const ySum = String(year).split("").reduce((a, b) => a + Number(b), 0);
  return reduceToDigit(day + month + ySum);
}

// Universal year of any calendar year
export function universalYear(year) {
  return reduceToDigit(String(year).split("").reduce((a, b) => a + Number(b), 0));
}

