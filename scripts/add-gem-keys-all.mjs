function block(code) {
  const out = {};
  for (const p of PLANETS) {
    FIELDS.forEach((f, i) => { out[`k_gem_${p}_${f}`] = GEM[code][p][i]; });
  }
  for (const [s, v] of Object.entries(MU[code])) out[`k_mu_${s}`] = v;
  for (const [c, v] of Object.entries(WHY[code])) out[`k_why_${c}`] = v;
  return out;
}

